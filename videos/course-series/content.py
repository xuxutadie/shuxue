lessons=[]
def lesson(number,title):
    item={'number':number,'title':title,'scenes':[]}
    lessons.append(item)
    return item
def scene(l,title,kind,texts,notes=None,**data):
    l['scenes'].append({'id':f"s{len(l['scenes'])+1}",'title':title,'kind':kind,'lines':[{'cue':f'l{i}','text':t} for i,t in enumerate(texts)],'notes':notes or [],'data':data})
def question(l,title,stem,lines):
    scene(l,title,'question',lines,stem=stem)
def challenge(l,stem,answer):
    scene(l,'现在，换你把思路讲明白','challenge',[
      '最后请你来当小老师。先把这道题完整读一遍，题目中的每个条件都要用自己的话说清楚。',
      stem,
      '现在暂停视频。你可以在草稿纸上画图和计算，准备好后上台讲解自己的解法。讲完再检查答案是否满足题目的条件。'
    ],stem=stem)
    l['scenes'][-1]['lines'][-1]['pause']=12
    l['challengeAnswer']=answer

